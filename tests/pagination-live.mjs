const response = (name, predicate = () => true) => page.waitForResponse(r => r.url().endsWith('/rpc/' + name) && r.status() === 200 && predicate(r.request().postDataJSON()));
async function belowList(id, rows) {
  const pager = page.getByTestId(id + '-pagination');
  await expect(pager).toHaveCount(1);
  await expect(rows.first()).toBeVisible();
  const result = await pager.evaluate((el, selector) => {
    const rows = [...document.querySelectorAll(selector)];
    const last = rows.at(-1);
    return { pagerY: el.getBoundingClientRect().top + scrollY, lastBottom: last.getBoundingClientRect().bottom + scrollY, after: !!(last.compareDocumentPosition(el) & Node.DOCUMENT_POSITION_FOLLOWING), controlsAbove: [...document.querySelectorAll('.ps-pagination')].filter(nav => nav.getBoundingClientRect().top < rows[0].getBoundingClientRect().top).length };
  }, rows === maintenanceRows ? '[data-testid="maintenance-venue-row"]' : id === 'venue-maintenance' ? '.maintenance-night' : id === 'support' ? '.support-ticket' : '.mcp-table tbody tr');
  assert(result.after && result.pagerY >= result.lastBottom && result.controlsAbove === 0, JSON.stringify(result));
  report.lists.push({ id, url: page.url(), count: await rows.count(), ...result });
}
const maintenanceRows = page.getByTestId('maintenance-venue-row');
