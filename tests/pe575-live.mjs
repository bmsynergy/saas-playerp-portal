import {readFile,writeFile,mkdir} from 'node:fs/promises';
import assert from 'node:assert/strict';
const origin=process.env.PORTAL_TEST_ORIGIN||'https://playerp.dev.bmore.app';
assert(['https://playerp.dev.bmore.app','http://127.0.0.1:18793'].includes(origin));
const out=process.env.LIVE_OUTPUT_DIR||'docs/evidence/pe575';
await mkdir(out,{recursive:true});
const accounts=JSON.parse(await readFile('/home/coredev/.coredeva-private/pe321-portal-dev/cuentas.json','utf8'));
const defaults=await readFile(new URL('../build/dev-defaults.ts',import.meta.url),'utf8');
const key=defaults.match(/SUPABASE_PUBLIC_KEY\s*=\s*['"]([^'"]+)/)[1];
const api='https://fzwzmwstxlsxdzdmphyq.supabase.co';
const login=await fetch(api+'/auth/v1/token?grant_type=password',{method:'POST',headers:{apikey:key,'Content-Type':'application/json'},body:JSON.stringify({email:accounts.staff_activo.email,password:accounts.staff_activo.password})});
assert.equal(login.status,200);const session=await login.json();
const browser=await chromium.launch({headless:true,executablePath:'/home/coredev/.cache/ms-playwright/chromium_headless_shell-1223/chrome-headless-shell-linux64/chrome-headless-shell',args:['--no-sandbox']});
const context=await browser.newContext({viewport:{width:1440,height:1000}});
await context.addInitScript(s=>{if(!sessionStorage.getItem('pe575.init')){localStorage.setItem('playerp.portal.dev.auth',JSON.stringify(s));localStorage.setItem('playerp.locale','es');sessionStorage.setItem('pe575.init','1');}},session);
const page=await context.newPage();page.setDefaultTimeout(30000);
const stamp=Date.now().toString(36);
const report={origin,at:new Date().toISOString(),stamp,errors:[],calls:[],criteria:{}};
page.on('pageerror',e=>report.errors.push(e.message));
page.on('response',r=>{if(/platform-tenant-onboard|rpc\/(portal_tenant_readiness|update_tenant_info)$/.test(r.url()))report.calls.push({url:r.url().split('/').slice(-1)[0],status:r.status()});});
try {
  await page.goto(origin+'/admin');
  await expect(page.getByTestId('new-tenant')).toBeVisible();
  await page.screenshot({path:`${out}/1-admin-boton.png`});
  await page.getByTestId('new-tenant').click();
  await expect(page).toHaveURL(/\/admin\/tenants\/new$/);
  await page.getByLabel('Nombre del local *').fill(`PE575 Tom ${stamp}`);
  assert.equal(await page.getByLabel('Nombre corto (slug) *').inputValue(),`pe575-tom-${stamp}`);
  await page.getByLabel('Ciudad').fill('San Juan');
  await page.getByRole('button',{name:'Continuar'}).click();
  await page.getByLabel('Correo del owner *').fill(`delivered+pe575-tom-${stamp}@resend.dev`);
  await page.getByLabel('Nombre *',{exact:true}).fill('Prueba');
  await page.getByLabel('Apellidos *').fill('PE575');
  await page.getByRole('button',{name:'Continuar'}).click();
  await page.screenshot({path:`${out}/2-revision.png`});
  await page.getByRole('button',{name:'Crear tenant'}).click();
  await expect(page.getByText('Tenant creado')).toBeVisible({timeout:60000});
  await page.screenshot({path:`${out}/3-resultado.png`});
  report.criteria.wizard='created';
  await page.getByRole('link',{name:'Abrir ficha del local'}).click();
  await expect(page.getByText('Checklist de preparación')).toBeVisible();
  for (const k of ['basic_info','owner_access','stripe_connect','domain','operations']) await expect(page.locator(`[data-readiness="${k}"]`)).toBeVisible();
  report.criteria.readiness=await page.locator('.readiness-item').allInnerTexts();
  await page.screenshot({path:`${out}/4-ficha-checklist.png`,fullPage:true});
  await page.getByRole('button',{name:'Editar ficha'}).click();
  await page.getByLabel('Teléfono').fill('7875550175');
  await page.getByRole('button',{name:'Guardar cambios'}).click();
  await expect(page.getByText('Cambios guardados.')).toBeVisible();
  await expect(page.locator('.detail-grid')).toContainText('7875550175');
  report.criteria.edit='saved';
  report.venue_url=page.url();
  await page.screenshot({path:`${out}/5-ficha-editada.png`,fullPage:true});
} catch(e) { report.failure=String(e); await page.screenshot({path:`${out}/fallo.png`,fullPage:true}).catch(()=>{}); }
await writeFile(`${out}/report-${origin.includes('127.0.0.1')?'local':'dev'}.json`,JSON.stringify(report,null,1));
await browser.close();
console.log(JSON.stringify(report,null,1));
if(report.failure||report.errors.length)process.exit(1);
